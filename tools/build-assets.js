/*
 * Turns the Figma art in assets/ into js/assets.js (one small script file).
 *
 * Why: the exported tree picture (PNG / PDF) is drawn from a single SVG, and an SVG that is
 * turned into an image cannot load other files. So the leaf shapes and the bark picture are
 * put inside the script and added to the SVG when the tree is drawn.
 *
 * Run after you change anything in assets/:   node tools/build-assets.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const dir = path.join(root, 'assets');

// where each leaf joins the twig (the notch at the round end), in the leaf's own pixels
const BASES = [[22, 113.5], [16, 103], [20, 114], [13, 97]];
// the thin lines of a leaf are drawn thicker, because the leaf is shown small
const LINE_BOOST = [2.2, 1.8, 2.4];

const leaves = BASES.map(function (base, i) {
  const svg = fs.readFileSync(path.join(dir, 'leaf-' + (i + 1) + '.svg'), 'utf8');
  const vb = svg.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/);
  const defs = svg.match(/<defs>([\s\S]*?)<\/defs>/)[1].trim();
  const inner = svg.replace(/<defs>[\s\S]*?<\/defs>/, '').replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  const paths = inner.match(/<path[^>]*\/>/g).slice(0, 3).map(function (p, k) {
    return p.replace(/stroke-width="([\d.]+)"/, function (m, w) {
      return 'stroke-width="' + (parseFloat(w) * LINE_BOOST[k]).toFixed(2) + '"';
    });
  });
  return { w: +vb[1], h: +vb[2], bx: base[0], by: base[1], defs: defs, body: paths.join('') };
});

const bark = 'data:image/jpeg;base64,' + fs.readFileSync(path.join(dir, 'bark.jpg')).toString('base64');

const out =
  '/* GENERATED by tools/build-assets.js from the Figma art in assets/. Do not edit by hand. */\n' +
  '(function (root) {\n' +
  "  'use strict';\n" +
  '  root.FT = root.FT || {};\n' +
  '  root.FT.assets = ' + JSON.stringify({ leaves: leaves, bark: bark }) + ';\n' +
  "})(typeof self !== 'undefined' ? self : globalThis);\n";

fs.writeFileSync(path.join(root, 'js', 'assets.js'), out);
console.log('js/assets.js written: ' + leaves.length + ' leaves, bark ' + Math.round(bark.length / 1024) + ' KB, total ' + Math.round(out.length / 1024) + ' KB');
