/*
 * Puts the photo-real art (made in Figma, cut by tools/make-photo-assets.py) into js/assets.js.
 *
 * Why: the exported tree picture (PNG / PDF) is drawn from one SVG, and an SVG that is turned into
 * an image cannot load other files. So the pictures are put inside the script as data and added to the
 * SVG when the tree is drawn.
 *
 * Steps after you change a picture in assets/photo/:
 *   python3 tools/make-photo-assets.py     (cuts leaves, makes the seamless bark and foliage tiles)
 *   node tools/build-assets.js             (writes js/assets.js)
 */
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const dir = path.join(root, 'assets', 'photo', 'processed');

function png(p) {
  const b = fs.readFileSync(p);
  return { uri: 'data:image/png;base64,' + b.toString('base64'), w: b.readUInt32BE(16), h: b.readUInt32BE(20) };
}
function jpg(p) {
  const b = fs.readFileSync(p);
  let i = 2;
  while (i < b.length) {                       // find the size marker of the JPEG
    if (b[i] !== 0xff) { i++; continue; }
    const m = b[i + 1];
    if (m >= 0xc0 && m <= 0xcf && m !== 0xc4 && m !== 0xc8 && m !== 0xcc) {
      return { uri: 'data:image/jpeg;base64,' + b.toString('base64'), w: b.readUInt16BE(i + 7), h: b.readUInt16BE(i + 5) };
    }
    i += 2 + b.readUInt16BE(i + 2);
  }
  throw new Error('no size in ' + p);
}

const leaves = [];
for (let i = 1; fs.existsSync(path.join(dir, 'leaf-' + i + '.png')); i++) leaves.push(png(path.join(dir, 'leaf-' + i + '.png')));
const bark = jpg(path.join(dir, 'bark-tile.jpg'));
const foliage = jpg(path.join(dir, 'foliage-tile.jpg'));
const bg = jpg(path.join(dir, 'background.jpg'));

const assets = {
  photo: true,
  leaves: leaves,                      // each leaf: tip up, stalk at the bottom centre
  leafLen: 190,                        // height of a leaf picture in pixels
  bark: bark.uri, barkSize: bark.w, barkScale: 0.42,
  foliage: foliage.uri, foliageSize: foliage.w, foliageScale: 0.9,
  bg: { uri: bg.uri, w: bg.w, h: bg.h, meadowTop: 0.64, topColor: '#8cbeeb' }
};

const out =
  '/* GENERATED by tools/build-assets.js from assets/photo/. Do not edit by hand. */\n' +
  '(function (root) {\n' +
  "  'use strict';\n" +
  '  root.FT = root.FT || {};\n' +
  '  root.FT.assets = ' + JSON.stringify(assets) + ';\n' +
  "})(typeof self !== 'undefined' ? self : globalThis);\n";

fs.writeFileSync(path.join(root, 'js', 'assets.js'), out);
console.log('js/assets.js written: ' + leaves.length + ' leaves, bark ' + bark.w + 'px, foliage ' + foliage.w + 'px, background ' + bg.w + 'x' + bg.h + ', total ' + Math.round(out.length / 1024) + ' KB');
